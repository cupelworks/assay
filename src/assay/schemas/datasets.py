import uuid
from pathlib import Path

from pydantic import BaseModel, Field, field_validator

from assay.schemas import Pagination
from assay.timestamps import Timestamp


class DataSetImportViaPathRequest(BaseModel):
    path: str = Field(
        ...,
        description="Path to the dataset to be imported.",
    )
    dataset_name: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="The name of the dataset.",
    )

    @field_validator('path')
    @classmethod
    def must_be_jsonl(cls, v: str) -> str:
        if Path(v).suffix != '.jsonl':
            raise ValueError("Path must point to a jsonl file.")
        return v


class DataSetID(BaseModel):
    id: uuid.UUID = Field(
        ...,
        description="The ID of the dataset, generated by the database.",
    )


class DataSetName(BaseModel):
    name: str = Field(
        ...,
        description="The name of the dataset.",
    )


class DataSetInfo(DataSetID, DataSetName):
    pass


class DataRowInfo(BaseModel):
    n: int = Field(
        ...,
        description="The number of loaded records.",
    )
    ids: list[uuid.UUID] = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )


class DataSetImportedData(BaseModel):
    dataset: DataSetInfo
    loaded: DataRowInfo


class DataSetImportViaPathResponse(DataSetImportedData):
    path: str = Field(
        ...,
        description="Path to the dataset to be imported.",
    )


class DataSetDeletedData(BaseModel):
    dataset: DataSetInfo
    deleted: DataRowInfo


class DataSetRowSchema(BaseModel):
    prompt: str = Field(
        ...,
        description="The prompt or message sent by the user.",
    )
    expected_output: str = Field(
        ...,
        description="The Ground Truth for the prompt.",
    )
    model_output: str = Field(
        ...,
        description="The answer your application gave for this prompt. Leave it empty "
                    "for tests that ask the application under test instead: a test made "
                    "from a row with a blank model_output has no recorded answer.",
    )


class DataSetImportingData(DataSetID):
    rows: list[DataSetRowSchema]


class DataSetDeletingData(BaseModel):
    row_ids: list[uuid.UUID] = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )


class DataSetRow(BaseModel):
    id: uuid.UUID = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )
    row_info: DataSetRowSchema


class DataSetRowUpdatedData(BaseModel):
    dataset: DataSetInfo
    updated: DataRowInfo


class DataSetMetadata(DataSetID, DataSetName):
    created_at: Timestamp = Field(
        ...,
        description="The creation date of the dataset.",
    )
    row_count: int = Field(description="How many rows it has.")
    first_prompt: str | None = Field(
        description="Its first row's prompt (the lowest number), or null when it has no rows.")


class DataSetRowRead(DataSetRow):
    """A dataset row as it's read: its content, its number and its tests."""
    number: int = Field(description="Its number within the dataset, from 1. A deleted row "
                                    "leaves a gap, so a row keeps its number, and the tests "
                                    "made from it show the same (`dataset_row_number`).")
    test_count: int = Field(description="How many tests were made from it.")


class PaginatedDataSetResponse(Pagination):
    items: list[DataSetMetadata]


class PaginatedDataSetRowResponse(DataSetID, Pagination):
    items: list[DataSetRowRead]
