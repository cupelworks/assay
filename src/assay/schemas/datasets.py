import uuid
from pathlib import Path

from pydantic import BaseModel, Field, field_validator


class DataSetImportViaPathRequest(BaseModel):
    path: str = Field(
        ...,
        description="Path to the dataset to be imported.",
    )
    dataset_name: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="The name of the dataset.",
    )

    @field_validator('path')
    @classmethod
    def must_be_jsonl(cls, v: str) -> str:
        if Path(v).suffix != '.jsonl':
            raise ValueError("Path must point to a jsonl file.")
        return v


class DataSetID(BaseModel):
    id: uuid.UUID = Field(
        ...,
        description="The ID of the dataset, generated by the database.",
    )


class DataSetInfo(DataSetID):
    name: str = Field(
        ...,
        description="The name of the dataset.",
    )


class DataRowInfo(BaseModel):
    n: int = Field(
        ...,
        description="The number of loaded records.",
    )
    ids: list[uuid.UUID] = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )


class DataSetImportedData(BaseModel):
    dataset: DataSetInfo
    loaded: DataRowInfo


class DataSetImportViaPathResponse(DataSetImportedData):
    path: str = Field(
        ...,
        description="Path to the dataset to be imported.",
    )


class DataSetDeletedData(BaseModel):
    dataset: DataSetInfo
    deleted: DataRowInfo


class DataSetRowSchema(BaseModel):
    prompt: str = Field(
        ...,
        description="The prompt or message sent by the user.",
    )
    expected_output: str = Field(
        ...,
        description="The Ground Truth for the prompt.",
    )
    model_output: str = Field(
        ...,
        description="The answer of the model.",
    )


class DataSetImportingData(DataSetID):
    rows: list[DataSetRowSchema]


class DataSetDeletingData(BaseModel):
    row_ids: list[uuid.UUID] = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )


class DataSetRowToUpdate(BaseModel):
    id: uuid.UUID = Field(
        ...,
        description="The ID of the data records, generated by the database.",
    )
    row_info: DataSetRowSchema


class DataSetRowUpdatedData(BaseModel):
    dataset: DataSetInfo
    updated: DataRowInfo
